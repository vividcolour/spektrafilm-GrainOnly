#!/usr/bin/env python3
"""Generate src/StockData.h from spektrafilm film profiles (CC BY-SA 4.0).

Only camera (filming-stage) film stocks are exported. For each stock we keep the
characteristic density curves and the per-sublayer density curves, which drive
spektrafilm's sublayer particle grain model, plus an RMS granularity target used
to calibrate grain strength.

Usage: python3 tools/gen_stocks.py tools/profiles src/StockData.h
"""
import json
import math
import os
import sys

# Menu order, display label and diffuse RMS granularity target (x1000, density
# 1.0 above base, 48 um aperture). Values come from manufacturer data sheets
# where published (RMS); stocks Kodak rates with Print Grain Index instead are
# mapped to an approximate RMS equivalent.
STOCKS = [
    ("kodak_vision3_50d",      3.5),
    ("kodak_vision3_250d",     5.0),
    ("kodak_vision3_200t",     5.0),
    ("kodak_vision3_500t",     6.5),
    ("kodak_verita_200d",      5.0),
    ("kodak_portra_160",       4.0),
    ("kodak_portra_400",       4.5),
    ("kodak_portra_800",       6.0),
    ("kodak_portra_800_push1", 7.0),
    ("kodak_portra_800_push2", 8.5),
    ("kodak_ektar_100",        3.5),
    ("kodak_gold_200",         5.0),
    ("kodak_ultramax_400",     5.5),
    ("kodak_ektachrome_100",   8.0),
    ("kodak_kodachrome_64",   10.0),
    ("fujifilm_pro_400h",      4.5),
    ("fujifilm_c200",          5.0),
    ("fujifilm_xtra_400",      5.0),
    ("fujifilm_provia_100f",   8.0),
    ("fujifilm_velvia_100",    8.0),
]


def lit(v, digits=6):
    text = f"{v:.{digits}g}"
    if not any(ch in text for ch in ".en"):
        text += ".0"
    return text + "f"


def fmt(values):
    return ", ".join(lit(v) for v in values)


def main():
    profile_dir, out_path = sys.argv[1], sys.argv[2]
    lines = [
        "// Generated by tools/gen_stocks.py - do not edit.",
        "// Film data from spektrafilm profiles by Andrea Volpato, CC BY-SA 4.0.",
        "#pragma once",
        "",
        "namespace spektragrain {",
        "",
    ]
    entries = []
    for idx, (stock, rms) in enumerate(STOCKS):
        with open(os.path.join(profile_dir, stock + ".json")) as f:
            prof = json.load(f)
        info, data = prof["info"], prof["data"]
        assert info["stage"] == "filming", stock
        le = data["log_exposure"]
        dc = data["density_curves"]
        dl = data["density_curves_layers"]
        n = len(le)
        step = (le[-1] - le[0]) / (n - 1)
        for a, b in zip(le, le[1:]):
            assert abs((b - a) - step) < 1e-6, stock

        def clean(v):
            if v is None or (isinstance(v, float) and math.isnan(v)):
                return 0.0
            v = float(v)
            return v if v > 1e-9 else 0.0

        curves = [clean(dc[i][c]) for i in range(n) for c in range(3)]
        layers = [clean(dl[i][l][c]) for i in range(n) for l in range(3) for c in range(3)]
        lines.append(f"static const float kCurves{idx}[{n * 3}] = {{{fmt(curves)}}};")
        lines.append(f"static const float kLayers{idx}[{n * 9}] = {{{fmt(layers)}}};")
        entries.append(
            f'  {{"{info["name"]}", {"true" if info["type"] == "positive" else "false"}, '
            f"{rms:.2f}f, {lit(le[0])}, {lit(step, 9)}, {n}, kCurves{idx}, kLayers{idx}}},"
        )

    lines += [
        "",
        "struct StockProfile {",
        "  const char *name;",
        "  bool positive;         // reversal (slide) film",
        "  float rmsTarget;       // diffuse RMS granularity x1000",
        "  float logE0;           // first log10 exposure sample",
        "  float logEStep;        // uniform sample spacing",
        "  int count;             // samples",
        "  const float *curves;   // [count][3] density above base, rgb",
        "  const float *layers;   // [count][3 sublayer][3 rgb]",
        "};",
        "",
        "static const StockProfile kStocks[] = {",
        *entries,
        "};",
        f"static const int kStockCount = {len(entries)};",
        f"static const int kDefaultStock = {[s for s, _ in STOCKS].index('kodak_vision3_250d')};",
        "",
        "}  // namespace spektragrain",
        "",
    ]
    with open(out_path, "w") as f:
        f.write("\n".join(lines))
    print(f"wrote {len(entries)} stocks to {out_path}")


if __name__ == "__main__":
    main()
